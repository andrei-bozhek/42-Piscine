int	parse_input(char input[], int hint[2][4][2])
{
	int	i;

	i = 0;
	while (i < 16)
	{
		if (input[i * 2] < '1' || input[i * 2] > '4')
			return (1);
		if (i < 15 && input[i * 2 + 1] != ' ')
			return (1);
		if (i < 8)
			hint[0][i % 4][i / 4] = input[i * 2] - '0';
		else
			hint[1][i % 4][(i - 8) / 4] = input[i * 2] - '0';
		i++;
	}
	if (input[31] != '\0')
	{
		return (1);
	}
	return (0);
}
